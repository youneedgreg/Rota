export const LANGS = ["en", "fr"] as const;
export type Lang = (typeof LANGS)[number];

const dictionaries: Record<Lang, Record<MessageKey, string>> = { en, fr };

export type Vars = Record<string, string | number>;

/** The text for `key` in `lang`, with {placeholders} filled in. */
export function translate(lang: Lang, key: MessageKey, vars: Vars = {}): string {
  return dictionaries[lang][key].replace(/\{(\w+)\}/g, (whole, name: string) =>
    name in vars ? String(vars[name]) : whole,
  );
}

/** For Intl: dates and numbers in the reader's language. */
export function localeOf(lang: Lang): string | undefined {
  return lang === "fr" ? "fr-FR" : undefined;
}

/**
 * An error raised by the app itself. Its message is the English text, so logs
 * and English readers see the same thing; `explainError` shows it in French.
 */
export class UiError extends Error {
  constructor(
    readonly key: MessageKey,
    readonly vars: Vars = {},
  ) {
    super(translate("en", key, vars));
    this.name = "UiError";
  }
}
